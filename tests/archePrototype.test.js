import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = (path) => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('route arche conservée séparément du réseau pro et des rendez-vous', () => {
  const app=read('src/App.jsx')
  assert.match(app, /import ArchePage from '\.\/components\/ArchePage'/)
  assert.match(app, /p === '\/arche' \? 'arche'/)
  assert.match(app, /view === 'arche'[\s\S]*<ArchePage onBack=\{backHome\} onNavigate=\{legalNav\}/)
  assert.match(read('scripts/apply-lumia-assistant-console.mjs'), /view !== 'arche'/)
})

test('la découverte renvoie vers une page de connexion simulée puis une application', () => {
  const page=read('src/components/ArchePage.jsx')
  const experience=read('src/components/ArcheSocialPrototype.jsx')
  assert.match(page, /data-arche-prototype="v2"/)
  assert.match(page, /setScreen\('login'\)/)
  assert.match(page, /screen === 'login'/)
  assert.match(page, /ArcheLoginPreview onBack=/)
  assert.match(page, /screen === 'app'/)
  assert.match(page, /ArcheAppPreview nickname=\{appNickname\} onExit=/)
  assert.match(experience, /id="connexion"/)
  assert.match(experience, /J’ai un compte/)
  assert.match(experience, /Créer un compte/)
  assert.match(experience, /Ne saisissez aucun vrai mot de passe ici/)
  assert.match(experience, /aucun compte n’est créé, aucun message n’est envoyé/)
  assert.match(experience, /onEnter\(pseudo\.trim\(\)\)/)
})

