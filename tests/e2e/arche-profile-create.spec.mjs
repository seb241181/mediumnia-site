import { test, expect } from './arche-test-fixtures.mjs'
import { mkdirSync } from 'node:fs'
import { join } from 'node:path'
test.use({baseURL:process.env.ARCHE_BASE_URL || 'http://127.0.0.1:4173'})
async function open(page,width=390) {
  await page.setViewportSize({width,height:width===390?844:1000})
  await page.goto('/arche')
  await page.getByRole('button',{name:/Se connecter à L’Arche/}).click()
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:/Entrer dans l’application/}).click()
  const nav=page.getByRole('navigation',{name:width===390?'Navigation principale L’Arche':'Navigation latérale L’Arche',exact:true})
  await nav.getByRole('button',{name:'Rencontres',exact:true}).click()
}
for(const choice of ['Amitié','Amour','Les deux']) test('Création courte '+choice+' : âge, activation et filtres',async({page})=>{
  await open(page)
  const submit=page.getByRole('button',{name:'Créer mon profil',exact:true})
  await expect(submit).toBeDisabled()
  await expect(page.getByLabel('Pseudo',{exact:true})).toHaveValue('Étoile du Nord')
  await expect(page.getByRole('heading',{name:'Des personnes à découvrir'})).toHaveCount(0)
  await page.getByRole('radio',{name:choice,exact:true}).check()
  await expect(submit).toBeDisabled()
  await page.getByLabel('Pseudo',{exact:true}).fill('Solstice')
  await page.locator('#rencontre-bio').fill('Une conversation, un peu de musique et le plaisir de découvrir.')
  await expect(page.locator('#rencontre-bio')).toHaveAttribute('maxlength','300')
  await page.locator('#rencontre-region').fill('Bretagne')
  await page.getByRole('button',{name:'Photo simulée',exact:true}).click()
  await expect(page.locator('input[type=file]')).toHaveCount(0)
  await page.getByRole('checkbox',{name:/J’ai 18 ans ou plus/}).check()
  await submit.click()
  await expect(page.getByRole('heading',{name:'Des personnes à découvrir'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Relation amoureuse',exact:true})).toHaveCount(choice==='Amitié'?0:1)
  if(choice!=='Amitié') {
    await page.getByRole('button',{name:'Relation amoureuse',exact:true}).click()
    await expect(page.getByRole('article').filter({hasText:'Brin de Sauge'})).toBeVisible()
  }
  await page.getByRole('button',{name:'Mon profil Rencontres',exact:true}).click()
  await expect(page.locator('.arche-rencontre-own-summary')).toContainText('Solstice')
  await expect(page.locator('.arche-rencontre-own-summary')).toContainText('Bretagne')
  await page.getByRole('checkbox',{name:'Mon profil est visible des participants'}).uncheck()
  await expect(page.getByRole('heading',{name:'Des personnes à découvrir'})).toHaveCount(0)
  await page.reload()
  await page.getByRole('button',{name:/Se connecter à L’Arche/}).click()
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:/Entrer dans l’application/}).click()
  await page.getByRole('navigation',{name:'Navigation principale L’Arche',exact:true}).getByRole('button',{name:'Rencontres',exact:true}).click()
  await expect(page.getByLabel('Pseudo',{exact:true})).toHaveValue('Étoile du Nord')
  await expect(page.locator('#rencontre-bio')).toHaveValue('')
})
for(const width of [390,1440]) test('Capture fiche de création '+width,async({page},testInfo)=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  await open(page,width)
  await page.getByRole('radio',{name:'Les deux',exact:true}).check()
  await page.getByRole('button',{name:'Lune',exact:true}).click()
  await page.locator('#rencontre-bio').fill('J’aime les échanges spontanés, la musique et les balades. Au plaisir de faire connaissance.')
  await page.locator('#rencontre-region').fill('Lille')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  const dir=process.env.ARCHE_CAPTURE_DIR || testInfo.outputDir;mkdirSync(dir,{recursive:true})
  await page.getByRole('checkbox',{name:/J’ai 18 ans ou plus/}).check()
  await page.locator('#rencontre-region').blur()
  const submit=page.getByRole('button',{name:'Créer mon profil',exact:true})
  await expect(submit).toBeInViewport()
  if(width===390) { const box=await submit.boundingBox(); expect(box.y+box.height).toBeLessThanOrEqual(780) }
  await page.screenshot({path:join(dir,'creation-rencontres-'+width+'.png'),fullPage:false})
})
