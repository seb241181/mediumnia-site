test('messages privés seulement après invitation acceptée et Toc toc contrôlé', () => {
  const page=read('src/components/ArcheSocialPrototype.jsx')
  assert.match(page,/const \[contact,setContact\]=useState\('request'\)/)
  assert.match(page,/setContact\('accepted'\)/)
  assert.match(page,/contact==='accepted'/)
  assert.match(page,/contact!=='accepted'/)
  assert.match(page,/contact==='blocked'/)
  assert.match(page,/const \[allowToc,setAllowToc\]/)
  assert.match(page,/!allowToc\|\|contact!=='accepted'\|\|Date\.now\(\)-lastToc<10000/)
  assert.match(page,/typeof navigator\.vibrate==='function'/)
  assert.match(page,/navigator\.vibrate\(\[90,45,90\]\)/)
  assert.match(page,/prefers-reduced-motion:reduce/)
  assert.match(page,/vibration non disponible sur ce navigateur/)
  assert.doesNotMatch(page,/new Notification\(|new Audio\(/)
})

