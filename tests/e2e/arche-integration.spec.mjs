test.use({ baseURL: process.env.ARCHE_BASE_URL || 'http://127.0.0.1:4173' })
const nav = page => page.getByRole('navigation', { name: 'Navigation principale L’Arche', exact: true })
async function enter(page, width = 390, pseudo) {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
  await page.goto('/arche')
  await page.getByRole('button', { name: /Se connecter à L’Arche/ }).click()
  if (pseudo) await page.getByLabel('Pseudonyme fictif').fill(pseudo)
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: /Entrer dans l’application/ }).click()
}
async function go(page, label, width = 390) {
  const menu = width === 390 ? nav(page) : page.getByRole('navigation', { name: 'Navigation latérale L’Arche', exact: true })
  await menu.getByRole('button', { name: label, exact: true }).click()
}
async function participate(page, width = 390, all = false) {
  await go(page, 'Rencontres', width)
  for (const intent of all ? ['Amitié','Échanges et découvertes','Binôme de pratique','Affinités de cœur','Relation amoureuse'] : ['Amitié','Échanges et découvertes']) await page.getByRole('checkbox', { name: new RegExp('^'+intent) }).check()
  await page.getByRole('checkbox', { name: /J’ai 18 ans ou plus/ }).check()
  await page.getByRole('button', { name: 'Rejoindre les Rencontres' }).click()
}
async function acceptPhare(page) {
  await page.getByRole('article').filter({ hasText: 'Petit Phare aimerait' }).getByRole('button', { name: 'Accepter', exact: true }).click()
  await page.getByRole('button', { name: 'Écrire à Petit Phare', exact: true }).click()
  await expect(page.locator('#arche-dm-draft')).toBeVisible()
}
