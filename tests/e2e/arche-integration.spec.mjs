  await expect(messages.getByRole('button', { name: 'Envoyer une Lueur' })).toHaveCount(0)
  await page.getByLabel('Options de la conversation', { exact: true }).click()
  await expect(messages.getByRole('checkbox', { name: 'Autoriser les Lueurs de mes proches' })).toHaveCount(0)
  await expect(messages.getByRole('button', { name: 'Simuler une Lueur reçue' })).toHaveCount(0)
