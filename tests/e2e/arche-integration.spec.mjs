test('Aurore garde les personnalisations, le consentement Lueur et le délai local', async ({ page }) => {
  await page.clock.install(); await enter(page); await go(page,'Messages')
  await page.getByRole('button', { name: /Aurore/ }).first().click()
  await page.getByRole('button', { name: 'Accepter', exact: true }).click()
  await page.getByRole('button', { name: 'Bulles menthe', exact: true }).click()
  await page.getByRole('button', { name: 'Mon style', exact: true }).click()
  await page.getByRole('button', { name: 'Emoji étoile', exact: true }).click()
  await page.getByRole('button', { name: 'Terminé', exact: true }).click()
  await page.getByLabel('Options de la conversation', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Simuler une Lueur reçue' })).toBeDisabled()
  await page.getByRole('checkbox', { name: 'Autoriser les Lueurs de mes proches' }).check()
  await page.getByRole('button', { name: 'Simuler une Lueur reçue' }).click()
  await expect(page.locator('.arche-lueur-flash')).toHaveCount(1)
  await page.clock.fastForward(700)
  await page.getByRole('button', { name: 'Simuler une Lueur reçue' }).click()
  await expect(page.locator('.arche-lueur-flash')).toHaveCount(0)
  await page.getByLabel('Options de la conversation', { exact: true }).press('Escape')
  await page.getByRole('button', { name: 'Envoyer une Lueur' }).click()
  await expect(page.getByRole('button', { name: 'Envoyer une Lueur' })).toBeDisabled()
  await page.clock.fastForward(11000)
  await expect(page.getByRole('button', { name: 'Envoyer une Lueur' })).toBeEnabled()
  await page.emulateMedia({ reducedMotion:'reduce' })
  await page.getByRole('button', { name: 'Envoyer une Lueur' }).click()
  await expect(page.locator('.arche-lueur-flash')).toBeHidden()
})
for(const width of [390,1440]) test('Parcours et captures '+width+' px : une seule messagerie, design conservé', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion:'reduce' })
  await enter(page,width)
  const feed = page.locator('.arche-feed')
  await expect(feed.getByRole('heading', { name: 'Entre nous' })).toBeVisible()
  await expect(feed.locator('.arche-feed-avatar[data-person=aurore]')).toBeVisible()
  expect(await feed.locator('.arche-post').first().evaluate(el => el.getBoundingClientRect().top)).toBeLessThan(width === 390 ? 420 : 650)
  const captureDir=process.env.ARCHE_CAPTURE_DIR || testInfo.outputDir
  mkdirSync(captureDir,{recursive:true})
  await page.screenshot({path:pathJoin(captureDir,'correction-fil-'+width+'.png'),fullPage:false})
  await participate(page,width)
  await expect(page.locator('.arche-rencontres:visible #rencontres-title')).toHaveCSS('font-family', await feed.evaluate(el=>getComputedStyle(el).fontFamily))
  const dir=process.env.ARCHE_CAPTURE_DIR || testInfo.outputDir
  mkdirSync(dir,{recursive:true})
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.getByRole('button', { name:'Fermer', exact:true }).click()
  await page.screenshot({ path:pathJoin(dir,'correction-rencontres-'+width+'.png'),fullPage:true })
  await acceptPhare(page)
  await page.locator('#arche-dm-draft').fill('Bonjour, votre présentation m’a parlé. Prenons le temps de faire connaissance.')
  await page.getByRole('button', { name:'Envoyer',exact:true }).click()
  await page.evaluate(()=>window.scrollTo(0,0))
  await expect(page.locator('#rencontre-draft')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Envoyer une Lueur'})).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  await page.screenshot({ path:pathJoin(dir,'integration-messages-'+width+'.png'),fullPage:false })
  await go(page,'Fil',width)
  await expect(page.getByRole('heading',{name:'Entre nous'})).toBeVisible()
  await expect(page.locator('[data-logo-proposal=lueur]')).toBeVisible()
  await expect(page.locator('meta[name=robots]')).toHaveAttribute('content','noindex,nofollow')
})
